import {fileURLToPath} from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
const root=fileURLToPath(new URL('..',import.meta.url));
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const app=read('src/app.js');
const css=read('src/styles.css');
const state=read('src/core/default-state.js');
const failures=[];
const require=(ok,label)=>{if(!ok)failures.push(label)};
for(const token of ['patientCommandHeader','workflowBar','prontuarioPanel','resultsCenterHtml','closureReviewHtml','recordTabs','submitClinicalNote','requestFinishCase'])require(app.includes(token),`app:${token}`);
for(const token of ['patient-command','clinical-workflow','record-tabs','results-center','closure-review','premium-post','metric-bars'])require(css.includes(token),`css:${token}`);
for(const tab of ['overview','history','results','plan','vitals','timeline'])require(app.includes(`'${tab}'`),`record-tab:${tab}`);
require(app.includes('Ações ${clinicalProgress().actions}'),'HUD sem score previsto');
require(!app.includes('Score previsto ${calcScore()}/100'),'score previsto removido');
require(app.includes('onclick="requestFinishCase()"'),'encerramento protegido');
require(app.includes('onclick="confirmFinishCase()"'),'confirmação final');
require(state.includes("recordTab:'overview'"),'estado recordTab');
require(state.includes('closureReview:false'),'estado closureReview');
require(state.includes('resultsOpen:false'),'estado resultsOpen');
if(failures.length)throw new Error(`Auditoria da interface clínica falhou: ${failures.join(' | ')}`);
console.log(JSON.stringify({ok:true,patientCommand:true,workflowSteps:5,recordTabs:6,resultsCenter:true,closureReview:true,predictedScoreVisible:false},null,2));
