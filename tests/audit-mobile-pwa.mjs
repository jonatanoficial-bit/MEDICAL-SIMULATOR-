import {fileURLToPath} from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
const root=fileURLToPath(new URL('..',import.meta.url));
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const manifest=JSON.parse(read('manifest.webmanifest'));
const index=read('index.html');
const css=read('src/styles.css');
const app=read('src/app.js');
const mobile=read('src/core/mobile-experience.js');
const sw=read('sw.js');
const failures=[];
const require=(ok,label)=>{if(!ok)failures.push(label)};
require(manifest.display==='fullscreen','manifest display fullscreen');
require(manifest.display_override?.includes('standalone'),'display override standalone');
require(manifest.icons?.some(x=>x.purpose==='maskable'),'ícone maskable');
require(manifest.icons?.some(x=>x.sizes==='512x512'),'ícone 512');
for(const icon of manifest.icons||[])require(fs.existsSync(path.join(root,icon.src)),`arquivo ${icon.src}`);
require(index.includes('viewport-fit=cover'),'viewport safe area');
require(index.includes('apple-mobile-web-app-capable'),'meta iOS PWA');
require(index.includes('apple-touch-icon'),'apple touch icon');
for(const token of ['env(safe-area-inset-bottom)','--app-height','shift-mobile-tabs','mobile-shift-dock','min-height:var(--touch-target)'])require(css.includes(token),`CSS ${token}`);
for(const token of ["['summary','👤','Resumo']",'setShiftTab','mobileClinicalStrip','installGame'])require(app.includes(token),`app ${token}`);
for(const token of ['beforeinstallprompt','visualViewport','requestFullscreen','displayMode','isOrientationRequired','refresh:()=>emit()'])require(mobile.includes(token),`mobile ${token}`);
for(const token of ['selectAudience','chooseGameMode','onboardingCountries','data-avatar'])require(app.includes(token),`onboarding ${token}`);
require(sw.includes("VERSION='2.0.0'"),'versão SW');
require(sw.includes('icon-maskable-512.png'),'ícone no cache SW');
require(sw.includes('navigationPreload'),'navigation preload');
if(failures.length)throw new Error(`Auditoria mobile/PWA falhou: ${failures.join(' | ')}`);
console.log(JSON.stringify({ok:true,display:manifest.display,icons:manifest.icons.length,clinicalTabs:7,safeAreas:true,dynamicViewport:true},null,2));
