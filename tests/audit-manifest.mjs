import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const root=path.resolve(new URL('..',import.meta.url).pathname);
const manifest=JSON.parse(fs.readFileSync(path.join(root,'BUILD_MANIFEST.json'),'utf8'));
const walk=dir=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(entry=>entry.isDirectory()?walk(path.join(dir,entry.name)):[path.join(dir,entry.name)]);
const files=walk(root).filter(file=>path.relative(root,file).replaceAll('\\','/')!=='BUILD_MANIFEST.json').sort();
const actual=new Map(files.map(file=>{const data=fs.readFileSync(file);return [path.relative(root,file).replaceAll('\\','/'),{size:data.length,sha256:crypto.createHash('sha256').update(data).digest('hex')}];}));
const declared=new Map(manifest.files.map(item=>[item.path,item]));
const missing=[...declared.keys()].filter(file=>!actual.has(file));
const unlisted=[...actual.keys()].filter(file=>!declared.has(file));
const mismatch=[...actual].filter(([file,meta])=>{const item=declared.get(file);return item&&(item.size!==meta.size||item.sha256!==meta.sha256);}).map(([file])=>file);
const empty=[...actual].filter(([,meta])=>meta.size===0).map(([file])=>file);
if(manifest.version!=='0.27.0'||manifest.fileCount!==actual.size||missing.length||unlisted.length||mismatch.length||empty.length)throw new Error(JSON.stringify({version:manifest.version,fileCount:manifest.fileCount,actual:actual.size,missing,unlisted,mismatch,empty},null,2));
console.log(JSON.stringify({ok:true,version:manifest.version,files:actual.size,missing:0,unlisted:0,hashMismatch:0,empty:0},null,2));
