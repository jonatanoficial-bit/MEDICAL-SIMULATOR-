import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createCareerState,careerMetrics,canAdvanceCareer,advanceCareer,startCareerExam,answerCareerExam,recordCareerActivity,unlockedDepartments} from '../src/simulation/career-engine.js';
const registry=JSON.parse(fs.readFileSync(new URL('../data/career.json',import.meta.url),'utf8'));
const career=createCareerState(registry,{stageId:'intern'});
assert.equal(career.stageId,'intern');
assert.ok(unlockedDepartments(registry,career).includes('triage'));
for(let i=0;i<3;i++)recordCareerActivity(career,{type:'case',specialty:'clinica-medica',score:80,id:'case-'+i});
const completed=[{score:80},{score:80},{score:80}];
const metrics=careerMetrics(career,{completed,academyPassed:2,emergencyCompleted:0,outpatientCompleted:0,player:{xp:500,reputation:'Boa'}});
let check=canAdvanceCareer(registry,career,metrics);
assert.equal(check.ok,false);
assert.equal(check.next.id,'r1');
assert.equal(startCareerExam(career,registry,'exam-r1').ok,true);
for(let i=0;i<3;i++)answerCareerExam(career,registry,0);
assert.equal(career.examResults['exam-r1'].passed,true);
check=canAdvanceCareer(registry,career,metrics);
assert.equal(check.ok,true);
const promoted=advanceCareer(registry,career,metrics);
assert.equal(promoted.advanced,true);
assert.equal(career.stageId,'r1');
assert.ok(unlockedDepartments(registry,career).includes('outpatient-clinic'));
console.log(JSON.stringify({ok:true,stage:career.stageId,score:career.examResults['exam-r1'].score,activities:career.totalActivities}));
